let seq = 0
const ev = (kind: string, f: Record<string, unknown>) =>
  ({ sessionId: 'session-1', seq: ++seq, tsNanos: seq * 1000, kind, ...f }) as unknown as VizEvent
const co = (kind: string, id: string, label: string) =>
  ev(kind, { coroutineId: id, jobId: `j-${id}`, parentCoroutineId: null, scopeId: 's', label })

const session: SessionSnapshot = {
  sessionId: 'session-1',
  coroutineCount: 2,
  eventCount: 4,
  coroutines: [
    { id: 'c-1', jobId: 'j-c-1', parentId: null, scopeId: 's', label: 'order-1', state: 'ACTIVE' as CoroutineState },
    { id: 'c-2', jobId: 'j-c-2', parentId: null, scopeId: 's', label: 'order-2', state: 'SUSPENDED' as CoroutineState },
  ],
}

function wrapper({ children }: { children: ReactNode }) {
  return createElement(
    QueryClientProvider,
    { client: new QueryClient({ defaultOptions: { queries: { retry: false } } }) },
    children
  )
}

let page: HTMLDivElement | null = null

/** The session page as a demo shows it: header with every pill, main view, dock, a node selected. */
async function renderPage() {
  // order-1 holds a lock that order-2 waits for, so both cards have Part 4's second line.
  const lock = { mutexId: 'm-1', mutexLabel: 'inventory-lock' }
  const events = [
    ev('MutexCreated', { ...lock, ownerCoroutineId: null }),
    co('coroutine.started', 'c-1', 'order-1'),
    ev('MutexLockAcquired', { ...lock, acquirerId: 'c-1', acquirerLabel: 'order-1', waitDurationNanos: 0 }),
    co('coroutine.started', 'c-2', 'order-2'),
    ev('MutexQueueChanged', { ...lock, waitingCoroutineIds: ['c-2'], waitingLabels: ['order-2'] }),
    ev('coroutine.suspended', {
      coroutineId: 'c-2', jobId: 'j-c-2', parentCoroutineId: null, scopeId: 's', label: 'order-2',
      waitKind: 'MUTEX', resourceId: 'm-1', reason: 'mutex',
    }),
  ]
  vi.mocked(useEventStream).mockReturnValue({
    events,
    isConnected: true,
    error: null,
    clearEvents: vi.fn(),
    droppedCount: 1,
    receivedCount: events.length,
    reconnect: vi.fn(),
  } as unknown as ReturnType<typeof useEventStream>)
  vi.mocked(useSession).mockReturnValue({
    data: session,
    isLoading: false,
    refetch: vi.fn(),
  } as unknown as ReturnType<typeof useSession>)
  // Inside the page wrapper the route draws around the workspace.
  page = document.body.appendChild(document.createElement('div'))
  page.setAttribute('data-look-part', 'page')
  render(
    createElement(LookProvider, {
      link: 'a',
      children: createElement(SessionWorkspace, {
        sessionId: 'session-1',
        scenarioId: 'sync/combined/ecommerce',
        scenarioName: 'E-commerce Orders',
        startLive: true,
      }),
    }),
    { wrapper, container: page.appendChild(document.createElement('div')) }
  )
  await userEvent.click(screen.getByRole('button', { name: 'Open source for order-2' }))
}

