describe('A · Compact on the real page', () => {
  beforeEach(() => {
    localStorage.clear()
    seq = 0
    document.documentElement.setAttribute('data-look', 'a')
  })
  afterEach(() => {
    document.documentElement.removeAttribute('data-look')
    page?.remove()
    page = null
  })

  it('every rule of the look matches something on the page (a renamed hook fails here, not silently)', async () => {
    const all = [...partSelectors, ...cardSelectors]
    await renderPage()
    const onDemo = new Set(all.filter(selector => document.querySelectorAll(selector).length > 0))
    cleanup()
    page?.remove()
    await renderBigApp()
    const unmatched = all.filter(selector => !onDemo.has(selector) && document.querySelectorAll(selector).length === 0)
    expect(unmatched).toEqual([])
    expect(cardSelectors.length).toBeGreaterThan(10)
  })

  it('styles the header’s action buttons, and only those, as the sketch’s small buttons', async () => {
    await renderPage()
    const selector = "[data-look='a'] [data-look-part='header-actions'] button"
    const names = [...document.querySelectorAll(selector)].map(
      b => b.getAttribute('aria-label') ?? b.textContent?.trim()
    )
    expect(names).toEqual(['Scenario Running', 'Replay', 'Pause view', 'Export', 'More actions'])
  })

  it('turns only the state filter chips into legend items, not the view switch or Maximise', async () => {
    await renderPage()
    const chips = [
      ...document.querySelectorAll(
        "[data-look='a'] [data-look-part='main'] [role='group'][aria-label='Coroutine state'] > button[aria-pressed]"
      ),
    ].map(b => b.getAttribute('aria-label'))
    expect(chips).toEqual(['Active 1', 'Suspended 1'])
    const toolbarButtons = [
      ...document.querySelectorAll("[data-look='a'] [data-look-part='main-toolbar'] > button"),
    ].map(b => b.textContent?.trim())
    expect(toolbarButtons).toEqual(['Maximise'])
  })

  it('flattens both Inspector columns’ cards and rules off the second column', async () => {
    await renderPage()
    const cards = [
      ...document.querySelectorAll("[data-look='a'] [data-look-part='dock'] [data-testid='inspector'] section[data-testid]"),
    ].map(card => card.getAttribute('data-testid'))
    expect(cards).toEqual(expect.arrayContaining(['identity-card', 'events-card']))
    const second = document.querySelector(
      "[data-look='a'] [data-look-part='dock'] [data-testid='inspector'] > div:last-child > div + div"
    )
    expect(second).toBeInstanceOf(HTMLElement)
    expect(second!.querySelector("[data-testid='events-card']")).toBeInstanceOf(HTMLElement)
  })
})
