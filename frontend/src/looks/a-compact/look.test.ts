/** A's layout rules (everything before the generated colour block), comments removed. */
const layoutCss = css.slice(0, css.indexOf('/* --- generated by')).replace(/\/\*[\s\S]*?\*\//g, '')

/**
 * Every style rule of the layout CSS with its own declarations, also those of an at-rule
 * nested in it (`sel { @media (…) { decl } }` counts as `sel` with `decl`).
 */
function parseRules(text: string): { selectors: string[]; body: string }[] {
  const out: { selectors: string[]; body: string }[] = []
  const stack: { prelude: string; body: string }[] = []
  let buffer = ''
  for (const ch of text) {
    if (ch === '{') {
      stack.push({ prelude: buffer.trim(), body: '' })
      buffer = ''
    } else if (ch === '}') {
      const block = stack.pop()!
      block.body += buffer
      buffer = ''
      // The nearest style rule (not an at-rule) owns these declarations.
      const owner = [block, ...stack.slice().reverse()].find(b => !b.prelude.startsWith('@'))
      if (owner && owner !== block) owner.body += block.body
      if (!block.prelude.startsWith('@')) {
        out.push({ selectors: block.prelude.split(',').map(s => s.trim()), body: block.body })
      }
    } else if (ch === ';' && stack.length) {
      stack[stack.length - 1]!.body += buffer + ';'
      buffer = ''
    } else {
      buffer += ch
    }
  }
  return out
}

const rules = parseRules(layoutCss)

/** Selectors that style an element of the session page (not the look's root block). */
const partSelectors = rules
  .flatMap(rule => rule.selectors)
  .filter(selector => selector !== "html[data-look='a']")

/**
 * The card rules' selectors that the test page can show: pseudo-elements stripped, and
 * without the states and the children label it does not have (two root coroutines,
 * one active and one suspended).
 */
const cardSelectors = parseRules(cardCss)
  .flatMap(rule => rule.selectors)
  .map(selector => selector.replace(/::[\w-]+$/, ''))
  .filter(selector => !/data-state='(?!ACTIVE'|SUSPENDED')/.test(selector) && !selector.includes('node-children'))

describe('A · Compact', () => {
  it('is the trial look "a", labelled as the ⋯ menu shows it, with no layout slot of its own (CSS only)', () => {
    expect(compact).toEqual({ id: 'a', label: 'A · Compact', trial: true })
  })

  it('leaves the graph’s cards to card.css, whose size card.ts gives the layout', () => {
    expect(layoutCss).not.toMatch(/data-look-part='node/)
    expect(compactCard).toEqual({ width: 188, height: 66, fitMinZoom: 1 })
  })

  it('fits a root and six children side by side at full size on a 1440 px window', () => {
    // The graph is 1,417 px wide there (1440 minus the main view's padding), and lays cards
    // 40 px apart inside 32 px of padding (CoroutineTreeGraph's H_GAP and PADDING).
    expect(6 * compactCard.width + 5 * 40 + 2 * 32).toBeLessThanOrEqual(1417)
    expect(compactCard.fitMinZoom).toBe(1)
  })

  it('keeps every word on the card at 12 px or more, each part sizing its own text', () => {
    // A part left to the shared classes would inherit text-xs: 11.25 px at A's 15 px root.
    const sizes = [...cardCss.matchAll(/font-size:\s*([\d.]+)px/g)].map(m => Number(m[1]))
    expect(Math.min(...sizes)).toBeGreaterThanOrEqual(12)
    const rulesOf = parseRules(cardCss)
    for (const part of ['node-name', 'node-state', 'node-activity', 'node-children']) {
      const own = rulesOf
        .filter(rule => rule.selectors.some(sel => sel.endsWith(`[data-look-part='${part}']`)))
        .map(rule => rule.body)
        .join(';')
      expect(own, part).toMatch(/font-size:\s*(1[2-9]|[2-9]\d)px/)
    }
  })

  it('never hides keyboard focus', () => {
    expect(layoutCss).not.toMatch(/outline(-style|-width)?\s*:\s*(none|0)\b/)
    expect(layoutCss).not.toMatch(/--tw-ring-[\w-]*\s*:\s*0/)
  })

  it('draws the dock tabs’ focus ring inside the tab, where the sideways-scrolling tab row cannot clip it', () => {
    const tabRules = rules.filter(rule =>
      rule.selectors.includes("[data-look='a'] [data-look-part='dock-tabs'] > [role='tab']")
    )
    expect(tabRules.map(rule => rule.body).join()).toMatch(/--tw-ring-inset:\s*inset;/)
  })

  it('uses !important only to beat the state chips’ inline border', () => {
    const important = rules.filter(rule => rule.body.includes('!important'))
    expect(important.map(rule => rule.selectors)).toEqual([
      ["[data-look='a'] [data-look-part='main'] [role='group'][aria-label='Coroutine state'] > button[aria-pressed='false']"],
    ])
    expect(important[0]!.body.trim()).toBe('border-color: transparent !important;')
  })
})

