const css = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'tokens.css'), 'utf8')

/** A's layout rules (everything before the generated colour block), comments removed. */
const layoutCss = css.slice(0, css.indexOf('/* --- generated by')).replace(/\/\*[\s\S]*?\*\//g, '')

/**
 * Every style rule of the layout CSS with its own declarations, also those of an at-rule
 * nested in it (`sel { @media (…) { decl } }` counts as `sel` with `decl`).
 */
function parseRules(text: string): { selectors: string[]; body: string }[] {
  const out: { selectors: string[]; body: string }[] = []
  const stack: { prelude: string; body: string }[] = []
  let buffer = ''
  for (const ch of text) {
    if (ch === '{') {
      stack.push({ prelude: buffer.trim(), body: '' })
      buffer = ''
    } else if (ch === '}') {
      const block = stack.pop()!
      block.body += buffer
      buffer = ''
      // The nearest style rule (not an at-rule) owns these declarations.
      const owner = [block, ...stack.slice().reverse()].find(b => !b.prelude.startsWith('@'))
      if (owner && owner !== block) owner.body += block.body
      if (!block.prelude.startsWith('@')) {
        out.push({ selectors: block.prelude.split(',').map(s => s.trim()), body: block.body })
      }
    } else if (ch === ';' && stack.length) {
      stack[stack.length - 1]!.body += buffer + ';'
      buffer = ''
    } else {
      buffer += ch
    }
  }
  return out
}

const rules = parseRules(layoutCss)

/** Selectors that style an element of the session page (not the look's root block). */
const partSelectors = rules
  .flatMap(rule => rule.selectors)
  .filter(selector => selector !== "html[data-look='a']")

describe('A · Compact', () => {
  it('is the trial look "a", labelled as the ⋯ menu shows it, with no layout slot of its own (CSS only)', () => {
    expect(compact).toEqual({ id: 'a', label: 'A · Compact', trial: true })
  })

  it('never sets a colour on the graph’s node cards: their state colours are shared by every look', () => {
    const nodeRules = rules.filter(rule => rule.selectors.some(s => s.includes("data-look-part='node'")))
    expect(nodeRules.length).toBeGreaterThan(0)
    for (const { body } of nodeRules) {
      expect(body).not.toMatch(/(^|[\s;])(color|background[\w-]*|border-color|border(-top|-right|-bottom|-left)?|fill|stroke)\s*:/)
    }
  })

  it('never hides keyboard focus', () => {
    expect(layoutCss).not.toMatch(/outline(-style|-width)?\s*:\s*(none|0)\b/)
    expect(layoutCss).not.toMatch(/--tw-ring-[\w-]*\s*:\s*0/)
  })

  it('uses !important only to beat the state chips’ inline border', () => {
    const important = rules.filter(rule => rule.body.includes('!important'))
    expect(important.map(rule => rule.selectors)).toEqual([
      ["[data-look='a'] [data-look-part='main'] [role='group'][aria-label='Coroutine state'] > button[aria-pressed='false']"],
    ])
    expect(important[0]!.body.trim()).toBe('border-color: transparent !important;')
  })
})

// --- The selectors match the real page -------------------------------------------------

let seq = 0
const ev = (kind: string, f: Record<string, unknown>) =>
  ({ sessionId: 'session-1', seq: ++seq, tsNanos: seq * 1000, kind, ...f }) as unknown as VizEvent
const co = (kind: string, id: string, label: string) =>
  ev(kind, { coroutineId: id, jobId: `j-${id}`, parentCoroutineId: null, scopeId: 's', label })

const session: SessionSnapshot = {
  sessionId: 'session-1',
  coroutineCount: 2,
  eventCount: 4,
  coroutines: [
    { id: 'c-1', jobId: 'j-c-1', parentId: null, scopeId: 's', label: 'order-1', state: 'ACTIVE' as CoroutineState },
    { id: 'c-2', jobId: 'j-c-2', parentId: null, scopeId: 's', label: 'order-2', state: 'SUSPENDED' as CoroutineState },
  ],
}

function wrapper({ children }: { children: ReactNode }) {
  return createElement(
    QueryClientProvider,
    { client: new QueryClient({ defaultOptions: { queries: { retry: false } } }) },
    children
  )
}

let page: HTMLDivElement | null = null

/** The session page as a demo shows it: header with every pill, main view, dock, a node selected. */
async function renderPage() {
  const events = [
    co('coroutine.created', 'c-1', 'order-1'),
    co('coroutine.started', 'c-1', 'order-1'),
    co('coroutine.created', 'c-2', 'order-2'),
    co('coroutine.suspended', 'c-2', 'order-2'),
  ]
  vi.mocked(useEventStream).mockReturnValue({
    events,
    isConnected: true,
    error: null,
    clearEvents: vi.fn(),
    droppedCount: 1,
    receivedCount: events.length,
    reconnect: vi.fn(),
  } as unknown as ReturnType<typeof useEventStream>)
  vi.mocked(useSession).mockReturnValue({
    data: session,
    isLoading: false,
    refetch: vi.fn(),
  } as unknown as ReturnType<typeof useSession>)
  // Inside the page wrapper the route draws around the workspace.
  page = document.body.appendChild(document.createElement('div'))
  page.setAttribute('data-look-part', 'page')
  render(
    createElement(SessionWorkspace, {
      sessionId: 'session-1',
      scenarioId: 'sync/combined/ecommerce',
      scenarioName: 'E-commerce Orders',
      startLive: true,
    }),
    { wrapper, container: page.appendChild(document.createElement('div')) }
  )
  await userEvent.click(screen.getByRole('button', { name: 'Open source for order-2' }))
}

describe('A · Compact on the real page', () => {
  beforeEach(() => {
    localStorage.clear()
    seq = 0
    document.documentElement.setAttribute('data-look', 'a')
  })
  afterEach(() => {
    document.documentElement.removeAttribute('data-look')
    page?.remove()
    page = null
  })

  it('every rule of the look matches something on the page (a renamed hook fails here, not silently)', async () => {
    await renderPage()
    const unmatched = partSelectors.filter(selector => document.querySelectorAll(selector).length === 0)
    expect(unmatched).toEqual([])
  })

  it('styles the header’s action buttons, and only those, as the sketch’s small buttons', async () => {
    await renderPage()
    const selector = "[data-look='a'] [data-look-part='header'] > div:first-child > div:last-child button"
    const names = [...document.querySelectorAll(selector)].map(
      b => b.getAttribute('aria-label') ?? b.textContent?.trim()
    )
    expect(names).toEqual(['Scenario Running', 'Replay', 'Pause view', 'Export', 'More actions'])
  })

  it('turns only the state filter chips into legend items, not the view switch or Maximise', async () => {
    await renderPage()
    const chips = [
      ...document.querySelectorAll(
        "[data-look='a'] [data-look-part='main'] [role='group'][aria-label='Coroutine state'] > button[aria-pressed]"
      ),
    ].map(b => b.getAttribute('aria-label'))
    expect(chips).toEqual(['Active 1', 'Suspended 1'])
    const toolbarButtons = [
      ...document.querySelectorAll("[data-look='a'] [data-look-part='main'] > div:first-child > button"),
    ].map(b => b.textContent?.trim())
    expect(toolbarButtons).toEqual(['Maximise'])
  })

  it('flattens both Inspector columns’ cards and rules off the second column', async () => {
    await renderPage()
    const cards = [
      ...document.querySelectorAll("[data-look='a'] [data-look-part='dock'] [data-testid='inspector'] section[data-testid]"),
    ].map(card => card.getAttribute('data-testid'))
    expect(cards).toEqual(expect.arrayContaining(['identity-card', 'events-card']))
    const second = document.querySelector(
      "[data-look='a'] [data-look-part='dock'] [data-testid='inspector'] > div:last-child > div + div"
    )
    expect(second?.querySelector("[data-testid='events-card']")).not.toBeNull()
  })
})
